"""Copy the P32W documents the website uses into stage/, keeping each file's repository path, so the links between
them keep working. The source is this repository's working tree, read only: nothing here writes to it.

The repository is private, so a visitor cannot follow a link to GitHub: what the site needs is copied here (the design
documents, the PDF books, each card's schematic and placement PDFs and its KiCad renders, resized), and hooks.py turns
a link to any other repository file into plain text.

Generated on top of the copies: the home page (home.md here), "The repository" page (the repository README), the
codespace page (.devcontainer/README.md, as codespace.md), and one
"Board" page per card (hardware/<card>/board.md: its renders and PDFs).

Never on the site: software/micropython (third-party), the build outputs (software/build), Claude's notes
(CLAUDE.md), node_modules."""
import glob, os, re, shutil
from PIL import Image

REPO = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))   # the repository this folder is in
HERE = os.path.dirname(os.path.abspath(__file__))
OUT = os.path.join(HERE, "stage")
# the boards, in slot order (docs/architecture.md); the backplane is not a card
BOARDS = ["backplane", "cpu-card", "mmu-card", "mem-card", "disk-card", "io-card", "video-card", "debug-card"]
GLOBS = ["docs/*.md", "docs/pdf/*.pdf", "*/README.md", "*/*/README.md",
         "hardware/gal/README.md", "hardware/video-card/yacc1-v3/README.md",
         "hardware/*/kicad/*-schematic.pdf", "hardware/*/kicad/*-placement.pdf"]
SKIP = re.compile(r"(^|/)(micropython|build|node_modules)(/|$)|(^|/)CLAUDE\.md$")
RENDER_PX = 1400           # the KiCad renders are 2400 px; resized to fit this box


def write(rel, lines):
    path = os.path.join(OUT, rel)
    os.makedirs(os.path.dirname(path), exist_ok=True)
    open(path, "w", encoding="utf-8").write("\n".join(lines).rstrip() + "\n")


shutil.rmtree(OUT, ignore_errors=True)
paths = set()
for g in GLOBS:
    paths |= {os.path.relpath(p, REPO) for p in glob.glob(os.path.join(REPO, g))}
n = 0
for rel in sorted(paths):
    if SKIP.search(rel) or not os.path.isfile(os.path.join(REPO, rel)): continue
    dst = os.path.join(OUT, rel)
    os.makedirs(os.path.dirname(dst), exist_ok=True)
    shutil.copy2(os.path.join(REPO, rel), dst); n += 1
shutil.copy2(os.path.join(HERE, "home.md"), os.path.join(OUT, "index.md")); n += 1
shutil.copy2(os.path.join(REPO, "README.md"), os.path.join(OUT, "repository.md")); n += 1
# MkDocs leaves out folders whose names start with a dot: the codespace README is staged as codespace.md
shutil.copy2(os.path.join(REPO, ".devcontainer", "README.md"), os.path.join(OUT, "codespace.md")); n += 1

# --- each board's page: its KiCad renders (3D, top, bottom; generated by generators/build_board.sh) and PDFs. Every
# card is shown with its bus connectors at the bottom (Ken, 2026-10-27): the cards have J1-J3 on their left edge, so
# their renders are turned a quarter turn anticlockwise (the backplane is not a card)
VIEWS = [("3d", "3D view"), ("top", "top"), ("bottom", "bottom")]
for b in BOARDS:
    kicad = os.path.join(REPO, "hardware", b, "kicad")
    if not os.path.isdir(kicad): continue
    name = b.replace("-card", " card").replace("mmu", "MMU / data").replace("mem ", "memory ").replace("io ", "I/O ")
    name = name[0].upper() + name[1:]
    page = ["# %s: the board" % name, "",
            "The %s as laid out in KiCad, from the netlist in `generators/` (`build_board.sh`: placed, autorouted, "
            "checked). The renders show the parts without markings%s." % (name.lower(), "" if b == "backplane" else
            ", turned so the bus connectors are at the bottom"), ""]
    for view, title in VIEWS:
        src = os.path.join(kicad, "%s-render-%s.png" % (b, view))
        if not os.path.exists(src): continue
        im = Image.open(src)
        if b != "backplane": im = im.rotate(90, expand=True)
        im.thumbnail((RENDER_PX, RENDER_PX))
        dst = os.path.join(OUT, "hardware", b, "kicad", os.path.basename(src))
        os.makedirs(os.path.dirname(dst), exist_ok=True)
        im.save(dst, optimize=True); n += 1
        page += ["[![%s, %s](kicad/%s)](kicad/%s \"Open full size\")" % (name, title, os.path.basename(src),
                                                                       os.path.basename(src)), ""]
    pdfs = [("schematic", "Schematic"), ("placement", "Parts placement")]
    links = ["[%s (PDF)](kicad/%s-%s.pdf)" % (t, b, k) for k, t in pdfs if os.path.exists(os.path.join(kicad,
                                                                                    "%s-%s.pdf" % (b, k)))]
    if links: page += ["**Drawings:** " + " · ".join(links), ""]
    write("hardware/%s/board.md" % b, page); n += 1
print("staged %d files" % n)
