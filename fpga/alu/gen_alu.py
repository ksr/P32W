#!/usr/bin/env python3
"""Generate the ALU's code include and its test vectors from the single
sources (microcode/p32ucode.py for the codes; the reference below is
emulator/p32uemu.c alu() and the condition inputs, line for line).

    python3 gen_alu.py            # writes p32alu_codes.vh and alu_vectors.hex
"""
import os, sys, random
HERE = os.path.dirname(os.path.abspath(__file__))
sys.path.insert(0, os.path.join(HERE, "..", "..", "microcode"))
import p32ucode as UC

M = 0xFFFFFFFF
def s32(x): return x - (1 << 32) if x & 0x80000000 else x
def alu(op, a, b):
    o = {v: k for k, v in UC.ALU.items()}[op]
    if o == "ADD": return (a + b) & M
    if o == "SUB": return (a - b) & M
    if o == "AND": return a & b
    if o == "OR": return a | b
    if o == "XOR": return a ^ b
    if o == "NOR": return ~(a | b) & M
    if o == "SLL": return (a << (b & 31)) & M
    if o == "SRL": return a >> (b & 31)
    if o == "SRA": return (s32(a) >> (b & 31)) & M
    if o == "SLT": return int(s32(a) < s32(b))
    if o == "SLTU": return int(a < b)
    if o == "MUL": return (a * b) & M
    if o == "MULH": return ((s32(a) * s32(b)) >> 32) & M
    if o == "MULHU": return ((a * b) >> 32) & M
    if o == "DIV":
        if b == 0: return M
        if a == 0x80000000 and b == M: return 0x80000000
        q = abs(s32(a)) // abs(s32(b))                     # C: truncation toward zero
        return (q if (s32(a) < 0) == (s32(b) < 0) else -q) & M
    if o == "DIVU": return a // b if b else M
    if o == "REM":
        if b == 0: return a
        if a == 0x80000000 and b == M: return 0
        r = abs(s32(a)) % abs(s32(b))                      # C: sign of the dividend
        return (-r if s32(a) < 0 else r) & M
    if o == "REMU": return a % b if b else a
    if o == "PASSA": return a
    raise ValueError(o)

def main():
    with open(os.path.join(HERE, "p32alu_codes.vh"), "w") as fh:
        fh.write("// generated by gen_alu.py from microcode/p32ucode.py -- do not edit\n")
        for k, v in UC.ALU.items():
            fh.write("localparam [4:0] ALU_%s = 5'd%d;\n" % (k, v))
        fh.write("localparam [4:0] DOE_ALU = 5'd%d;\n" % UC.DOE["ALU"])
        fh.write("localparam [4:0] DLD_ALUA = 5'd%d;\nlocalparam [4:0] DLD_ALUB = 5'd%d;\n"
                 % (UC.DLD["ALUA"], UC.DLD["ALUB"]))
    rnd = random.Random(3)
    edge = [0, 1, 2, 3, 7, 31, 32, 0x7FFFFFFF, 0x80000000, 0x80000001, M, M - 1, 0x12345678, 0xDEADBEEF]
    rows = []
    for op in sorted(UC.ALU.values()):
        pairs = [(a, b) for a in edge for b in edge]
        pairs += [(rnd.getrandbits(32), rnd.getrandbits(32)) for _ in range(300)]
        pairs += [(rnd.getrandbits(32), rnd.getrandbits(rnd.randint(1, 31))) for _ in range(200)]
        for a, b in pairs:
            r = alu(op, a, b)
            flags = int(a == b) | int(s32(a) < s32(b)) << 1 | int(a < b) << 2
            rows.append("%02X%08X%08X%08X%02X" % (op, a, b, r, flags))   # one 112-bit word per line
    with open(os.path.join(HERE, "alu_vectors.hex"), "w") as fh:
        fh.write("\n".join(rows) + "\n")
    print("p32alu_codes.vh; %d vectors" % len(rows))

if __name__ == "__main__":
    main()
