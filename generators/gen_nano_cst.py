#!/usr/bin/env python3
"""The ALU module's FPGA pin constraints (D70): fpga/alu/p32alu_nano.cst, for
the Gowin IDE, from the CPU card's pin map of the Tang Nano 20K
(p32net.NANO_GPIO), so the FPGA project and the board cannot disagree.

    python3 generators/gen_nano_cst.py [FILE]

Ports are the CPU card's signal names, lower case, the buses indexed:
fd[15:0] (the operand / result bus, bidirectional), aluf[4:0], go, res_n
(inputs), selal_n, selah_n, selbl_n, selbh_n, cklo, ckhi (outputs). All
LVCMOS33: the module's banks are at 3.3 V; the CPU card's 74LVC latches
meet it there (D21).
"""
import os, sys, re

HERE = os.path.dirname(os.path.abspath(__file__))
sys.path.insert(0, HERE)
from p32net import NANO_GPIO, NANO_SHARED          # noqa: E402

def port(name):
    m = re.match(r"([A-Z]+)(\d+)$", name)
    if m and m.group(1) in ("FD", "ALUF"):
        return "%s[%s]" % (m.group(1).lower(), m.group(2))
    return name.lower()

def cst():
    L = ["// p32alu_nano.cst -- generated by generators/gen_nano_cst.py from the CPU card's",
         "// pin map (p32net.NANO_GPIO, D70): edit the generator, not this file.",
         "// The Tang Nano 20K's GW2AR-18 pins, from Sipeed's datasheet v1.3 (\"Pinout\").", ""]
    for name, gpio in sorted(NANO_GPIO.items(), key=lambda kv: kv[1]):
        if name.startswith("IO"):
            continue
        shared = NANO_SHARED.get(gpio, "")
        L.append('IO_LOC "%s" %d;%s' % (port(name), gpio, "  // also %s on the module" % shared if shared else ""))
        L.append('IO_PORT "%s" IO_TYPE=LVCMOS33 PULL_MODE=NONE;' % port(name))
    return "\n".join(L) + "\n"

if __name__ == "__main__":
    out = sys.argv[1] if len(sys.argv) > 1 else os.path.join(HERE, "..", "fpga", "alu", "p32alu_nano.cst")
    open(out, "w").write(cst())
    print("wrote " + out)
