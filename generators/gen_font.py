def glyphs():
    g = {}
    for line in GLYPHS.strip().splitlines():
        code, *rows = line.split()
        assert len(rows) == 8 and all(len(r) == 7 for r in rows), line
        g[int(code, 16)] = rows
    return g

def rom():
    """The ROM image: 4096 bytes (character x 16 + scan line)."""
    out = bytearray(4096)
    for code, rows in glyphs().items():
        for s in range(16):
            row = rows[s // 2]
            out[code * 16 + s] = sum(1 << (7 - x) for x, ch in enumerate(row) if ch == "#")
    return bytes(out)

# ---- the HD63484 card's font EPROM (docs/video-card-acrtc.md) ----
ACRTC_MW = 40                           # words a line at 640 dots
ACRTC_HALF = 48 * ACRTC_MW              # one half's bytes: 1,920
ACRTC_USED = 2 * ACRTC_HALF             # 3,840
ACRTC_SIZE = 32768                      # the 27C256

def acrtc_glyph(code):
    """16 bytes, top line first, bit 0 the left-hand dot"""
    rows = glyphs().get(code)
    if rows is None:
        return [0] * 16
    return [sum(1 << x for x, ch in enumerate(rows[s // 2]) if ch == "#") for s in range(16)]

def acrtc_address(code, line=0):
    """the EPROM byte that holds this line of the glyph of 0x20-0x7F"""
    row, place = (code - 0x20) >> 5, code & 0x1F
    return (place & 1) * ACRTC_HALF + (row * 16 + line) * ACRTC_MW + (place >> 1)

def acrtc_rom():
    """The 27C256's image: the font's picture twice, the rest 0."""
    out = bytearray(ACRTC_SIZE)
    for code in range(0x20, 0x80):
        for line, b in enumerate(acrtc_glyph(code)):
            out[acrtc_address(code, line)] = b
    assert not any(out[ACRTC_USED:])
    return bytes(out)

def acrtc_header():
    img = acrtc_rom()
    out = ["/* p32vfont.h -- GENERATED by generators/gen_font.py --acrtc-header: never edit.",
           "   The HD63484 card's font EPROM as the emulators hold it: the first",
           "   VFONT_USED bytes of its 32K image (the rest is 0). */",
           "#define VFONT_USED %d" % ACRTC_USED,
           "#define VFONT_HALF %d" % ACRTC_HALF,
           "#define VFONT_MW %d" % ACRTC_MW,
           "static const uint8_t vfont[VFONT_USED] = {"]
    for i in range(0, ACRTC_USED, 20):
        out.append("    " + ",".join("%d" % b for b in img[i:i + 20]) + ",")
    out.append("};")
    return "\n".join(out) + "\n"

def main():
    if len(sys.argv) > 1 and sys.argv[1] == "--acrtc-header":
        open(sys.argv[2], "w").write(acrtc_header())
        return
    if len(sys.argv) > 1 and sys.argv[1] == "--acrtc":
        path = sys.argv[2] if len(sys.argv) > 2 else os.path.join(ROOT, "video", "font-acrtc.bin")
        os.makedirs(os.path.dirname(path), exist_ok=True)
        open(path, "wb").write(acrtc_rom())
        print("font: %d glyphs as the HD63484 card's picture, %s" % (len(glyphs()), path))
        return
    path = sys.argv[1] if len(sys.argv) > 1 else os.path.join(ROOT, "video", "font8x16.bin")
    os.makedirs(os.path.dirname(path), exist_ok=True)
    open(path, "wb").write(rom().ljust(128 * 1024, b"\xff"))
    print("font: %d glyphs, %s" % (len(glyphs()), path))

if __name__ == "__main__":
    main()
