#!/usr/bin/env python3
"""The video card's font ROM (docs/video-card.md, D67): 256 characters x 16
scan lines, a byte per line, bit 7 the leftmost dot. Address = character x
16 + scan line (the card wires the scan line to A3-A0 and the character to
A11-A4, A12 and above to ground).

The glyphs are drawn here on an 8 x 8 grid (7 dots wide, the eighth column
the gap; capitals on rows 0-6, descenders on row 7) and each row is shown
on two scan lines, as an 8 x 8 font looks on a VGA screen. Printable ASCII
(20-7E); every other code is blank.

    python3 gen_font.py [OUT]       (default: video/font8x16.bin)

OUT is the whole SST39SF010A (128 KiB: the font, then FF), so the
programmer takes it as it is:  minipro -p SST39SF010A -w video/font8x16.bin

The same glyphs for the HD63484 card (docs/video-card-acrtc.md; D103, D104):

    python3 gen_font.py --acrtc [OUT]          (default: video/font-acrtc.bin)
    python3 gen_font.py --acrtc-header OUT     the emulators' copy (emulator/p32vfont.h)

That card's font EPROM (a 27C256) answers in the chip's frame buffer space
where MA19 is high (words 0x80000 up), its byte on both halves of the word,
bit 0 the left-hand dot. It holds the font as a picture the driver copies
into frame buffer RAM and draws every character from: 256 dots by 48
lines, the 96 glyphs of 0x20-0x7F in three rows of 32, the glyph of code c
at x = (c & 0x1F) x 8, 16 x ((c - 0x20) >> 5) lines down. A word of that
picture holds two glyphs, and the EPROM gives both halves of a word the
same byte, so it holds the picture twice, 40 bytes a line (the 640-dot
screen's memory width, which a copy steps by):

    line x 40 + w              the glyph at the even place 2w, lines 0-47
    1920 + line x 40 + w       the glyph at the odd place 2w + 1

Two masked copies (SCPY, mask 0x00FF then 0xFF00) put it together. The
layout is YACC1-D's (its tools/v3font.py); the glyphs are P32W's.
"""
