#!/usr/bin/env python3
"""Emit emulator/p32opc.h from microcode/p32isa.py (the ISA single source of
truth, D7). The header is a build artifact: edit p32isa.py, never the header.

    python3 gen_p32opc.py [-o ../emulator/p32opc.h]
"""
import os, sys, argparse

HERE = os.path.dirname(os.path.abspath(__file__))
sys.path.insert(0, os.path.join(HERE, "..", "microcode"))
from p32isa import OPC, FORMATS, FMT_ZERO, PRIVILEGED, CREGS, CAUSES  # noqa: E402

def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("-o", default=os.path.join(HERE, "..", "emulator", "p32opc.h"))
    ap.add_argument("--isa", default=os.path.join(HERE, "..", "software", "include", "p32isa.h"))
    a = ap.parse_args()
    out, isa_out = a.o, a.isa
    by_op = sorted(OPC.items(), key=lambda kv: kv[1][0])
    L = ["/* GENERATED by generators/gen_p32opc.py from microcode/p32isa.py -- do not edit. */",
         "#ifndef P32OPC_H", "#define P32OPC_H", "#include <stdint.h>", "",
         "enum p32fmt { F_ILLEGAL = 0, %s };" % ", ".join("F_" + f for f in FORMATS), ""]
    L += ["#define OP_%-6s 0x%02X" % (m, op) for m, (op, f) in by_op]
    L += ["", "static const char *const p32_name[256] = {"]
    L += ['    [0x%02X] = "%s",' % (op, m) for m, (op, f) in by_op]
    L += ["};", "", "static const unsigned char p32_fmt[256] = {"]
    L += ["    [0x%02X] = F_%s," % (op, f) for m, (op, f) in by_op]
    L += ["};", "", "/* bits that must be 0, per opcode */",
          "static const uint32_t p32_zmask[256] = {"]
    L += ["    [0x%02X] = 0x%08Xu," % (op, FMT_ZERO[f]) for m, (op, f) in by_op if FMT_ZERO[f]]
    L += ["};", "", "/* privileged: trap with PRIVILEGE in user mode */",
          "static const unsigned char p32_priv[256] = {"]
    L += ["    [0x%02X] = 1," % OPC[m][0] for m in sorted(PRIVILEGED, key=lambda m: OPC[m][0])]
    L += ["};", "", "/* control registers */"]
    L += ["#define CR_%-8s %d" % (n, v) for n, v in sorted(CREGS.items(), key=lambda kv: kv[1])]
    L += ["#define CR_COUNT    %d" % (max(CREGS.values()) + 1),
          "static const char *const p32_crname[16] = {"]
    L += ['    [%d] = "%s",' % (v, n) for n, v in sorted(CREGS.items(), key=lambda kv: kv[1])]
    L += ["};", "", "/* exception causes */"]
    L += ["#define EXC_%-11s %d" % (n, v) for n, v in sorted(CAUSES.items(), key=lambda kv: kv[1])]
    L += ["static const char *const p32_causename[16] = {"]
    L += ['    [%d] = "%s",' % (v, n) for n, v in sorted(CAUSES.items(), key=lambda kv: kv[1])]
    L += ["};", "", "#endif", ""]
    with open(out, "w") as fh:
        fh.write("\n".join(L))
    # the same table for programs on P32W Unix (the native as, M7): plain
    # initializers, which p32cc compiles
    N = ["/* GENERATED by generators/gen_p32opc.py from microcode/p32isa.py -- do not edit. */",
         "/* p32isa.h -- the P32W instruction set for programs on P32W Unix (the native as, M7, D24). */",
         "#ifndef _P32ISA_H", "#define _P32ISA_H", "",
         "enum p32fmt { F_ILLEGAL = 0, %s };" % ", ".join("F_" + f for f in FORMATS), "",
         "struct p32op { const char *name; int op, fmt; };",
         "static const struct p32op p32_ops[] = {"]
    N += ['    { "%s", 0x%02X, F_%s },' % (m, op, f) for m, (op, f) in sorted(OPC.items())]
    N += ["};", "#define P32_NOPS %d" % len(OPC), "",
          "/* control registers, by number */", "static const char *const p32_cregs[] = {"]
    N += ['    "%s",' % n for n, v in sorted(CREGS.items(), key=lambda kv: kv[1])]
    N += ["};", "#define P32_NCREGS %d" % len(CREGS), "", "#endif", ""]
    with open(isa_out, "w") as fh:
        fh.write("\n".join(N))

if __name__ == "__main__":
    main()
