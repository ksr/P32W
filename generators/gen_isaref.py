#!/usr/bin/env python3
"""Generate docs/instruction-reference.md from microcode/p32isa.py (the ISA's
single source of truth, D7): every instruction with its opcode, format,
syntax, privilege and a one-line meaning. Fails if an instruction has no
description, so a new instruction cannot go undocumented.

    python3 generators/gen_isaref.py [out.md]     (make test checks it is current)
"""
import os, sys
HERE = os.path.dirname(os.path.abspath(__file__))
sys.path.insert(0, os.path.join(HERE, "..", "microcode"))
from p32isa import OPC, PRIVILEGED, CREGS, CAUSES  # noqa: E402

SYNTAX = {"R": "rd, rs1, rs2", "I": "rd, rs1, simm16", "IU": "rd, rs1, uimm16", "SH": "rd, rs1, shamt",
          "LUI": "rd, uimm16", "LD": "rd, simm16(rs1)", "ST": "rs, simm16(rb)", "BR": "ra, rb, label",
          "J": "label", "JR": "rb", "N": "", "CR": "rd, cr  /  cr, rs",
          "X": "rd, rs1, rs2[, scale]", "P": "rd, off8(rs1), inc8", "L32": "rd, value32"}
MEANING = {
    "HALT": "stop the machine (emulators: exit status = r1 & 0xFF)",
    "ADD": "rd = rs1 + rs2", "SUB": "rd = rs1 − rs2", "AND": "rd = rs1 & rs2", "OR": "rd = rs1 | rs2",
    "XOR": "rd = rs1 ^ rs2", "NOR": "rd = ~(rs1 | rs2)",
    "SLL": "rd = rs1 << (rs2 & 31)", "SRL": "rd = rs1 >> (rs2 & 31), zero fill",
    "SRA": "rd = rs1 >> (rs2 & 31), sign fill",
    "SLT": "rd = (rs1 < rs2) signed ? 1 : 0", "SLTU": "rd = (rs1 < rs2) unsigned ? 1 : 0",
    "ADDI": "rd = rs1 + sext(imm)", "ANDI": "rd = rs1 & zext(imm)", "ORI": "rd = rs1 | zext(imm)",
    "XORI": "rd = rs1 ^ zext(imm)", "SLLI": "rd = rs1 << shamt", "SRLI": "rd = rs1 >> shamt, zero fill",
    "SRAI": "rd = rs1 >> shamt, sign fill", "SLTI": "rd = (rs1 < sext(imm)) signed",
    "SLTIU": "rd = (rs1 < sext(imm)) unsigned", "LUI": "rd = imm << 16",
    "MUL": "rd = low 32 bits of rs1 × rs2", "MULH": "rd = high 32 bits, signed × signed",
    "MULHU": "rd = high 32 bits, unsigned × unsigned",
    "DIV": "rd = rs1 / rs2 signed, toward zero (÷0 → −1; 0x80000000/−1 → 0x80000000)",
    "DIVU": "rd = rs1 / rs2 unsigned (÷0 → 0xFFFFFFFF)",
    "REM": "rd = rs1 % rs2 signed, sign of rs1 (÷0 → rs1; 0x80000000 % −1 → 0)",
    "REMU": "rd = rs1 % rs2 unsigned (÷0 → rs1)",
    "LB": "rd = sext(byte at rs1 + imm)", "LH": "rd = sext(halfword), aligned",
    "LW": "rd = word, aligned", "LBU": "rd = zext(byte)", "LHU": "rd = zext(halfword), aligned",
    "SB": "byte at rb + imm = rs", "SH": "halfword = rs, aligned", "SW": "word = rs, aligned",
    "SWAP": "exchange rd with the aligned word at rs1 + imm, atomically (D51)",
    "BEQ": "if ra == rb: PC = PC + 4 + 4 × off", "BNE": "if ra != rb", "BLT": "if ra < rb signed",
    "BGE": "if ra ≥ rb signed", "BLTU": "if ra < rb unsigned", "BGEU": "if ra ≥ rb unsigned",
    "JMP": "PC = PC + 4 + 4 × off24", "CALL": "push PC + 4; PC = PC + 4 + 4 × off24",
    "JR": "PC = rb (a multiple of 4)", "CALLR": "push PC + 4; PC = rb", "RET": "PC = pop",
    "SYSCALL": "trap SYSCALL (EPC = this instruction)", "BREAK": "trap BREAK",
    "RTE": "PC = EPC; S = PS; IE = PIE", "MFCR": "rd = control register cr", "MTCR": "control register cr = rs",
    "WAIT": "idle until (IPEND & IMASK) ≠ 0", "TLBW": "write TLBHI / TLBLO into the TLB entry TLBHI selects",
    # D59
    "LI32": "rd = the next word (two words; rd in field B)",
    "LBX": "rd = sext(byte at rs1 + rs2 × scale); scale 1, 2, 4 or 8", "LHX": "rd = sext(halfword at rs1 + rs2 × scale)",
    "LWX": "rd = word at rs1 + rs2 × scale", "LBUX": "rd = zext(byte at rs1 + rs2 × scale)",
    "LHUX": "rd = zext(halfword at rs1 + rs2 × scale)", "SBX": "byte at rs1 + rs2 × scale = rd",
    "SHX": "halfword at rs1 + rs2 × scale = rd", "SWX": "word at rs1 + rs2 × scale = rd",
    "LBP": "rd = sext(byte at rs1 + off8); then rs1 += inc8", "LHP": "rd = sext(halfword at rs1 + off8); rs1 += inc8",
    "LWP": "rd = word at rs1 + off8; rs1 += inc8 (rs1 written last)", "LBUP": "rd = zext(byte at rs1 + off8); rs1 += inc8",
    "LHUP": "rd = zext(halfword at rs1 + off8); rs1 += inc8", "SBP": "byte at rs1 + off8 = rd; rs1 += inc8",
    "SHP": "halfword at rs1 + off8 = rd; rs1 += inc8", "SWP": "word at rs1 + off8 = rd; rs1 += inc8",
}

def main():
    out = sys.argv[1] if len(sys.argv) > 1 else os.path.join(HERE, "..", "docs", "instruction-reference.md")
    missing = [m for m in OPC if m not in MEANING]
    if missing:
        sys.exit("gen_isaref: no description for %s" % ", ".join(missing))
    L = ["# P32W instruction reference", "",
         "*Generated by `generators/gen_isaref.py` from `microcode/p32isa.py` — do not edit.* "
         "Encodings: [isa-v0.md](isa-v0.md); system instructions: [isa-system.md](isa-system.md); "
         "how to use them: [programmers-guide.md](programmers-guide.md).", "",
         "Word: `OP[31:24] A[23:20] B[19:16] C[15:12] IMM16[15:0]` (or `OFF24[23:0]`). "
         "**P** = privileged (traps PRIVILEGE in user mode). Branch and jump offsets count "
         "words from PC + 4.", "",
         "| Op | Mnemonic | Operands | Format | P | Meaning |", "|---|---|---|---|---|---|"]
    for m, (op, fmt) in sorted(OPC.items(), key=lambda kv: kv[1][0]):
        L.append("| `%02X` | **%s** | `%s` | %s | %s | %s |" % (op, m, SYNTAX[fmt], fmt,
                 "P" if m in PRIVILEGED else "", MEANING[m].replace("|", "\\|")))
    L += ["", "## Control registers (MFCR / MTCR)", "", "| # | Name |", "|---|---|"]
    L += ["| %d | `%s` |" % (n, name) for name, n in sorted(CREGS.items(), key=lambda kv: kv[1])]
    L += ["", "## Exception causes (CAUSE)", "", "| Code | Name |", "|---|---|"]
    L += ["| %d | %s |" % (n, name) for name, n in sorted(CAUSES.items(), key=lambda kv: kv[1])]
    L += ["| 0x8000_0000 \\| v << 8 \\| n | interrupt on IRQn, v = the card's vector (D57) |", ""]
    with open(out, "w") as fh:
        fh.write("\n".join(L))
    print("%d instructions -> %s" % (len(OPC), out))

if __name__ == "__main__":
    main()
